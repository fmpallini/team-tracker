const dicts: Record<Locale, Record<MsgKey, string>> = {
  'pt-BR': pt,
  'en-US': en,
}

export function t(locale: Locale, key: MsgKey, params?: Record<string, string>): string {
  const msg = dicts[locale][key]
  if (!params) return msg
  // One pass over the message, rather than a split()/join() allocation per
  // param (t() runs hundreds of times per render). A `{name}` with no
  // matching param is left verbatim — same as the old per-param loop, which
  // simply never touched it. Single-pass, so an inserted value that happens
  // to contain `{other}` is not itself re-substituted.
  return msg.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? params[name]! : whole
  )
}

export function formatDate(iso: string, locale: Locale): string {
  const [y, m, d] = iso.split('-')
  if (locale === 'pt-BR') return `${d}/${m}/${y}`
  return `${m}/${d}/${y}`
}

/** Locale-ordered date (see formatDate) plus 24h time — for timestamps (backup last/next times) where the date alone would be ambiguous for an hourly interval. */
export function formatDateTime(ms: number, locale: Locale): string {
  const d = new Date(ms)
  const iso = `${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}`
  return `${formatDate(iso, locale)} ${pad2(d.getHours())}:${pad2(d.getMinutes())}`
}

/** formatDate() prefixed with the 3-letter weekday abbreviation (e.g. "Wed, 07/24/2026") — used for `@day` ref chips, where recalling the weekday at a glance matters more than in a plain due-date field. */
export function formatDateWithWeekday(iso: string, locale: Locale): string {
  const [y, m, d] = iso.split('-').map(Number) as [number, number, number]
  const dow = new Date(y, m - 1, d).getDay()
  return `${t(locale, `calendar_weekday_${dow}` as MsgKey)}, ${formatDate(iso, locale)}`
}

export function parseLocaleDate(s: string, locale: Locale): string | null {
  const parts = s.split('/')
  if (parts.length !== 3) return null
  const [a, b, c] = parts as [string, string, string]
  const dayStr = locale === 'pt-BR' ? a : b
  const monthStr = locale === 'pt-BR' ? b : a
  const yearStr = c
  if (!/^\d{1,4}$/.test(dayStr) || !/^\d{1,2}$/.test(monthStr) || !/^\d{4}$/.test(yearStr)) return null
  const day = Number(dayStr)
  const month = Number(monthStr)
  const year = Number(yearStr)
  if (!Number.isInteger(day) || !Number.isInteger(month) || !Number.isInteger(year)) return null

  const date = new Date(year, month - 1, day)
  if (date.getFullYear() !== year || date.getMonth() !== month - 1 || date.getDate() !== day) {
    return null
  }
  return `${year}-${pad2(month)}-${pad2(day)}`
}

export function todayIso(): string {
  const now = new Date()
  return `${now.getFullYear()}-${pad2(now.getMonth() + 1)}-${pad2(now.getDate())}`
}
